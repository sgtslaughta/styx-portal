#!/bin/bash
# Build agent/xwl_eager.c in docker (never on the host) and regenerate agent/xwl_eager.py.
set -euo pipefail
cd "$(dirname "$0")/.."
docker run --rm -v "$PWD/agent":/w -w /w gcc:14 bash -c \
  "gcc -shared -fPIC -O2 -s -Wl,--build-id=none -o /w/libstyx-xwl-eager.so xwl_eager.c \
   && chown $(id -u):$(id -g) /w/libstyx-xwl-eager.so"
python3 - <<'PY'
import base64, hashlib, pathlib
so = pathlib.Path("agent/libstyx-xwl-eager.so")
data = so.read_bytes()
so.unlink()
b64 = base64.b64encode(data).decode()
pathlib.Path("agent/xwl_eager.py").write_text(f'''"""Generated by scripts/build_xwl_eager.sh from xwl_eager.c -- do not edit.

LD_PRELOAD shim forcing mutter's eager Xwayland (see seat_gnome.py).
"""
import base64
import hashlib
from pathlib import Path

SO_SHA256 = "{hashlib.sha256(data).hexdigest()}"
SO_B64 = (
    "{b64}"
)  # noqa: E501


def write_so(path: Path) -> Path:
    """Write the .so to path (0o644) unless identical content is already there."""
    path = Path(path)
    data = base64.b64decode(SO_B64)
    try:
        if hashlib.sha256(path.read_bytes()).hexdigest() == SO_SHA256:
            return path
    except OSError:
        pass
    path.write_bytes(data)
    path.chmod(0o644)
    return path
''')
PY
